create or replace function public.toggle_post_heart(target_post_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if exists (
    select 1 from public.post_reactions
    where post_id = target_post_id and user_id = auth.uid()
  ) then
    delete from public.post_reactions
    where post_id = target_post_id and user_id = auth.uid();

    update public.posts
    set heart_count = greatest(heart_count - 1, 0), updated_at = now()
    where id = target_post_id;
  else
    insert into public.post_reactions (post_id, user_id)
    values (target_post_id, auth.uid());

    update public.posts
    set heart_count = heart_count + 1, updated_at = now()
    where id = target_post_id;
  end if;
end;
$$;

create or replace function public.mark_post_viewed(target_post_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.post_views (post_id, user_id)
  values (target_post_id, auth.uid())
  on conflict do nothing;

  update public.posts
  set view_count = (
    select count(*) from public.post_views where post_id = target_post_id
  ),
  updated_at = now()
  where id = target_post_id;
end;
$$;

create or replace function public.mark_post_shared(target_post_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.post_shares (post_id, user_id)
  values (target_post_id, auth.uid());

  update public.posts
  set share_count = share_count + 1, updated_at = now()
  where id = target_post_id;
end;
$$;

