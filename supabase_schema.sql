create extension if not exists "pgcrypto";

create table if not exists public.users (
  uid uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text not null default '',
  student_id text not null default '',
  college text not null default '',
  department text not null default '',
  year_level text not null default '',
  username text not null default '',
  role text not null default 'user',
  email_verified boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.profiles (
  uid uuid primary key references auth.users(id) on delete cascade,
  profile_picture_url text not null default '',
  full_name text not null default '',
  student_id text not null default '',
  college text not null default '',
  department text not null default '',
  year_level text not null default '',
  username text not null default '',
  bio text not null default '',
  skills text[] not null default '{}',
  portfolio_gallery text[] not null default '{}',
  availability_status text not null default 'available',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.posts (
  id uuid primary key default gen_random_uuid(),
  author_id uuid not null references auth.users(id) on delete cascade,
  author_name text not null default 'LNU student',
  author_email text not null default '',
  author_department text not null default '',
  type text not null check (
    type in (
      'Artwork showcase',
      'Commission open post',
      'Service promotion',
      'Progress update',
      'Announcement'
    )
  ),
  caption text not null default '',
  media_urls text[] not null default '{}',
  media_type text not null default 'none',
  heart_count integer not null default 0 check (heart_count >= 0),
  view_count integer not null default 0 check (view_count >= 0),
  share_count integer not null default 0 check (share_count >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.post_reactions (
  post_id uuid not null references public.posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  type text not null default 'heart' check (type = 'heart'),
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

create table if not exists public.post_views (
  post_id uuid not null references public.posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (post_id, user_id)
);

create table if not exists public.post_shares (
  id uuid primary key default gen_random_uuid(),
  post_id uuid not null references public.posts(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now()
);

create table if not exists public.listings (
  id int8 generated by default as identity primary key,
  title text not null default '',
  description text not null default '',
  price numeric not null default 0 check (price >= 0),
  category text not null default '',
  image_url text not null default '',
  seller_name text not null default '',
  seller_id text not null default '',
  created_at timestamptz not null default now()
);

create index if not exists listings_created_at_idx
on public.listings (created_at desc);

create index if not exists listings_seller_id_idx
on public.listings (seller_id);

create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.users (
    uid,
    email,
    full_name,
    student_id,
    college,
    department,
    year_level,
    username,
    email_verified
  )
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.raw_user_meta_data ->> 'student_id', ''),
    coalesce(new.raw_user_meta_data ->> 'college', ''),
    coalesce(new.raw_user_meta_data ->> 'department', ''),
    coalesce(new.raw_user_meta_data ->> 'year_level', ''),
    coalesce(new.raw_user_meta_data ->> 'username', ''),
    new.email_confirmed_at is not null
  )
  on conflict (uid) do update set
    email = excluded.email,
    full_name = excluded.full_name,
    student_id = excluded.student_id,
    college = excluded.college,
    department = excluded.department,
    year_level = excluded.year_level,
    username = excluded.username,
    email_verified = excluded.email_verified,
    updated_at = now();

  insert into public.profiles (
    uid,
    full_name,
    student_id,
    college,
    department,
    year_level,
    username
  )
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.raw_user_meta_data ->> 'student_id', ''),
    coalesce(new.raw_user_meta_data ->> 'college', ''),
    coalesce(new.raw_user_meta_data ->> 'department', ''),
    coalesce(new.raw_user_meta_data ->> 'year_level', ''),
    coalesce(new.raw_user_meta_data ->> 'username', '')
  )
  on conflict (uid) do nothing;

  return new;
end;
$$;

